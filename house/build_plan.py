import json, sys

def r(v): return round(v, 3)

def area(poly):
    s = 0.0
    for i in range(len(poly)):
        x1, y1 = poly[i]; x2, y2 = poly[(i + 1) % len(poly)]
        s += x1 * y2 - x2 * y1
    return abs(s) / 2

def rect(x1, y1, x2, y2): return [[x1, y1], [x2, y1], [x2, y2], [x1, y2]]

